USE restaurant_db;

-- ------------------------------------------------------------
-- 1. View all users
-- ------------------------------------------------------------
SELECT * FROM user;

-- ------------------------------------------------------------
-- 2. View all products
-- ------------------------------------------------------------
SELECT * FROM product;

-- ------------------------------------------------------------
-- 3. Filter products by price
-- ------------------------------------------------------------
SELECT name, price
FROM product
WHERE price > 40;

-- ------------------------------------------------------------
-- 4. Orders with specific status
-- ------------------------------------------------------------
SELECT *
FROM `order`
WHERE status = 'pending';

-- ------------------------------------------------------------
-- 5. Using AND (multiple conditions)
-- ------------------------------------------------------------
SELECT *
FROM `order`
WHERE status = 'pending' AND table_id = 1;

-- ------------------------------------------------------------
-- 6. Using OR (alternative conditions)
-- ------------------------------------------------------------
SELECT *
FROM product
WHERE price < 40 OR name = 'Latte';

-- ------------------------------------------------------------
-- 7. Order products by price (descending)
-- ------------------------------------------------------------
SELECT *
FROM product
ORDER BY price DESC;

-- ------------------------------------------------------------
-- 8. Filter users by email
-- ------------------------------------------------------------
SELECT name, email
FROM user
WHERE email LIKE '%gmail.com';
